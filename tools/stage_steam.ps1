[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$BuildDirectory,
    [uint32]$AppId,
    [uint32]$WindowsDepotId
)

$ErrorActionPreference = 'Stop'
$BuildRoot = (Resolve-Path -LiteralPath $BuildDirectory).Path
$SourceRoot = Join-Path $BuildRoot 'windows-x64'
$HasIds = $AppId -gt 0
if ($HasIds -ne ($WindowsDepotId -gt 0)) {
    throw 'Supply both Steamworks identifiers as positive integers, or omit both to create a template.'
}
$StageName = if ($HasIds) { "steam-staging-app-$AppId" } else { 'steam-staging' }
$Destination = Join-Path $BuildRoot $StageName
if (Test-Path -LiteralPath $Destination) {
    throw "A stage already exists in this build: $Destination"
}

$Manifest = Get-Content -LiteralPath (Join-Path $SourceRoot 'RELEASE_INFO.json') -Raw | ConvertFrom-Json
if ($Manifest.platform -ne 'windows-x64' -or $Manifest.source_dirty -ne $false -or
    $Manifest.version -notmatch '^[0-9A-Za-z.-]+$') {
    throw 'Expected a verified Windows release generated by tools/build_release.ps1.'
}
$Files = @('SigilsAndOaths.exe', 'SigilsAndOaths.pck', 'LICENSE.txt', 'RELEASE_INFO.json',
    'licenses/Godot-LICENSE.txt', 'licenses/Godot-COPYRIGHT.txt')
if ([version]($Manifest.version.Split('-')[0]) -ge [version]'0.60.0') { $Files += 'licenses/MUSIC-CREDITS.txt' }
$Entries = foreach ($Relative in $Files) {
    $Source = Get-Item -LiteralPath (Join-Path $SourceRoot $Relative)
    $Digest = (Get-FileHash -LiteralPath $Source.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($Relative -in @('SigilsAndOaths.exe', 'SigilsAndOaths.pck')) {
        $Expected = @($Manifest.payload | Where-Object file -eq $Relative)
        if ($Expected.Count -ne 1 -or $Expected[0].bytes -ne $Source.Length -or $Expected[0].sha256 -ne $Digest) {
            throw "Windows release data does not match its manifest: $Relative"
        }
    }
    [ordered]@{ file=$Relative; bytes=$Source.Length; sha256=$Digest }
}

$AppValue = if ($HasIds) { $AppId } else { '<APP_ID>' }
$DepotValue = if ($HasIds) { $WindowsDepotId } else { '<WINDOWS_DEPOT_ID>' }
$ScriptName = if ($HasIds) { "app_build_$AppId.vdf" } else { 'app_build.vdf.template' }
$BuildScript = @"
"AppBuild"
{
    "AppID" "$AppValue"
    "Desc" "Sigils and Oaths $($Manifest.version) Windows x64 preview"
    "Preview" "1"
    "ContentRoot" "..\content"
    "BuildOutput" "..\output"
    "Depots"
    {
        "$DepotValue"
        {
            "FileMapping"
            {
                "LocalPath" "*"
                "DepotPath" "."
                "Recursive" "1"
            }
        }
    }
}
"@
$Report = [ordered]@{
    version=$Manifest.version; source_commit=$Manifest.source_commit; platform='windows-x64';
    launch_executable='SigilsAndOaths.exe'; content_root='content';
    build_script="scripts/$ScriptName"; ids_supplied=$HasIds; preview_only=$true;
    files=$Entries
}

$PendingName = '.steam-staging-' + [Guid]::NewGuid().ToString('N')
$StageRoot = (New-Item -ItemType Directory -Path (Join-Path $BuildRoot $PendingName)).FullName
$StageRoot = (Resolve-Path -LiteralPath $StageRoot).Path
if ((Split-Path -Parent $StageRoot) -ne $BuildRoot -or (Split-Path -Parent $Destination) -ne $BuildRoot) {
    throw 'Staging paths must be direct children of the supplied build directory.'
}
try {
    foreach ($Directory in @('content/licenses', 'scripts', 'output')) {
        New-Item -ItemType Directory -Path (Join-Path $StageRoot $Directory) -Force | Out-Null
    }
    foreach ($Entry in $Entries) {
        $Relative = $Entry.file
        $Target = Join-Path $StageRoot "content/$Relative"
        Copy-Item -LiteralPath (Join-Path $SourceRoot $Relative) -Destination $Target
        if ((Get-FileHash -LiteralPath $Target -Algorithm SHA256).Hash -ne $Entry.sha256) {
            throw "Staged file failed verification: $Relative"
        }
    }
    Set-Content -LiteralPath (Join-Path $StageRoot $Report.build_script) -Value $BuildScript -Encoding ascii
    $Report | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $StageRoot 'STAGING_INFO.json') -Encoding utf8
    [IO.Directory]::Move($StageRoot, $Destination)
} finally {
    if (Test-Path -LiteralPath $StageRoot) {
        $Remaining = (Resolve-Path -LiteralPath $StageRoot).Path
        if ($Remaining -eq $StageRoot -and (Split-Path -Parent $Remaining) -eq $BuildRoot -and (Split-Path -Leaf $Remaining) -eq $PendingName) {
            Remove-Item -LiteralPath $Remaining -Recurse -Force
        }
    }
}
[pscustomobject]@{ stage=$Destination; script=(Join-Path $Destination $Report.build_script); files=$Entries.Count; launch=$Report.launch_executable } | ConvertTo-Json
